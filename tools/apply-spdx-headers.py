"""Put the license and copyright header on the first-party source files, and keep the rights holder consistent.

  apply-spdx-headers.py [--check] [--replace-holder OLD] [--root DIR] [-v]

Every first-party source file gets two comment lines at the top, below a shebang, a coding line and the
"dosplex-test:" declaration of the test runner:

    # SPDX-License-Identifier: AGPL-3.0-or-later
    # Copyright 2026 <rights holder>

(C files use /* ... */ and QML files //). The rights holder is the one line in legal/RIGHTS_HOLDER. The script is
idempotent: a file that has the header is left alone, a file that has only the SPDX line gets the copyright line,
and a second run changes nothing. It also writes the same name into NOTICE, AUTHORS.md and README.md (the lines
listed in IDENTITY); --check compares instead of writing.

Which files: the files of the directories in COVERED that git tracks (or that are not ignored), by extension or
name, or by a shebang. Left alone, and counted as such: the development-only tree and the other directories in
OUTSIDE, data files (DATA), files that say "Generated by wayland-scanner" in their first lines, and the paths that
legal/spdx-exclusions.txt lists with a reason (tracked binaries, a stray fragment). Third-party code gets no
DosPlex header: a file that has a copyright line of its own and no SPDX line, or an SPDX line other than the current
one, is reported and not touched. So is a file of a type nobody has classified, and an exclusion that matches no
file. An SPDX line of another identifier is never rewritten, except that --replace-holder also moves the legacy
identifier Apache-2.0 (LEGACY_LICENSE_IDS) to the current one, on files whose copyright line is ours.

To change the rights holder: edit legal/RIGHTS_HOLDER, then run this script with --replace-holder and the old name.
Without that option a header that names someone else is reported and never rewritten.

Exit status: 0 when every file is in order (after the changes, unless --check), 1 when --check finds a change to
make or any run finds a problem. Standard library only.
"""
import argparse
import collections
import fnmatch
import os
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
LICENSE_ID = 'AGPL-3.0-or-later'
LEGACY_LICENSE_IDS = ('Apache-2.0',)   # the identifier before the 2026-11-17 change; rewritten only with --replace-holder
COPYRIGHT_YEAR = '2026'
HOLDER_FILE = 'legal/RIGHTS_HOLDER'
EXCLUSIONS_FILE = 'legal/spdx-exclusions.txt'

# Top-level directories whose files get headers, and top-level directories (and files in the root) that never do.
COVERED = ('compositor', 'guest', 'packaging', 'prototype', 'scripts', 'tests', 'tools', 'vm')
OUTSIDE = ('.github', 'compatibility', 'docs', 'legal', 'private', 'website')
# How a type of file writes a comment: 'hash' (#), 'c' (/* ... */) or 'slashes' (//).
STYLES = {'.py': 'hash', '.sh': 'hash', '.service': 'hash', '.rules': 'hash', '.wrap': 'hash', '.c': 'c', '.h': 'c',
          '.qml': 'slashes', '.mjs': 'slashes'}
NAMES = {'meson.build': 'hash', 'meson_options.txt': 'hash', 'PKGBUILD': 'hash', 'Containerfile': 'hash'}
DATA = {'.json', '.md', '.txt', '.yaml', '.yml', '.lock', '.png', '.jpg', '.jpeg'}
GENERATED = re.compile(rb'Generated by wayland-scanner')
WINDOW = 30     # lines at the top of a file in which a header is looked for

SPDX_LINE = re.compile(r'^[ \t]*(?:#|//|/\*|\*)[ \t]*SPDX-License-Identifier:[ \t]*(.*?)[ \t]*(?:\*/)?[ \t]*$')
COPYRIGHT_LINE = re.compile(r'^[ \t]*(?:#|//|/\*|\*)[ \t]*(?:\(c\)[ \t]*|©[ \t]*)?Copyright\b')
OWN_COPYRIGHT = re.compile(r'^[ \t]*(?:#|//|/\*)[ \t]*Copyright \d{4} (?P<name>.*?)[ \t]*(?:\*/)?[ \t]*$')
CODING_LINE = re.compile(rb'^[ \t\f]*#.*?coding[:=][ \t]*[-\w.]+')
DECLARATION = re.compile(rb'^#\s*dosplex-(?:test|run):')

# The lines of public files that name the rights holder: (file, a pattern with the groups name and, optionally, year).
IDENTITY = (
    ('NOTICE', re.compile(r'^Copyright (?:© )?(?P<year>\d{4}) (?P<name>.+?)\.?$', re.M)),
    ('AUTHORS.md', re.compile(r'^\*\*(?P<name>.+?)\*\* — project author and maintainer', re.M)),
    ('README.md', re.compile(r'^Copyright © (?P<year>\d{4}) (?P<name>.+?)\.$', re.M)),
    ('README.md', re.compile(r'Created and maintained by \*\*(?P<name>.+?)\*\*', re.M)),
)


class HeaderProblem(Exception):
    """A file that this script must not change, with the reason."""


# --- The inputs ----------------------------------------------------------------------------------------------

def read_rights_holder(root=ROOT):
    """The name in legal/RIGHTS_HOLDER: exactly one non-empty line."""
    path = Path(root) / HOLDER_FILE
    try:
        names = [line.strip() for line in path.read_text(encoding='utf-8').splitlines() if line.strip()]
    except OSError as error:
        raise SystemExit('apply-spdx-headers: cannot read %s: %s' % (path, error.strerror or error))
    if len(names) != 1 or any(ord(character) < 32 for character in names[0]):
        raise SystemExit('apply-spdx-headers: %s must hold exactly one line, the name of the rights holder' % path)
    return names[0]


def read_exclusions(root=ROOT):
    """([(glob, reason)], problems) from legal/spdx-exclusions.txt: lines of "<path or glob> <reason>"."""
    path = Path(root) / EXCLUSIONS_FILE
    if not path.is_file():
        return [], []
    entries, problems = [], []
    for number, line in enumerate(path.read_text(encoding='utf-8').splitlines(), 1):
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        fields = line.split(None, 1)
        if len(fields) < 2:
            problems.append('%s:%d: an entry needs a path and a reason' % (EXCLUSIONS_FILE, number))
        elif fields[0].startswith('/') or '..' in fields[0].split('/'):
            problems.append('%s:%d: the path must stay inside the repository' % (EXCLUSIONS_FILE, number))
        else:
            entries.append((fields[0], fields[1]))
    return entries, problems


def list_files(root):
    """Sorted repository-relative paths of the files in the tree: those git tracks or does not ignore, or every
    file when the tree is not a git work tree (an exported tree, a test fixture)."""
    root = Path(root)
    names = None
    if (root / '.git').exists():
        try:
            # Not the repository that GIT_DIR, GIT_INDEX_FILE and the like point at (a hook sets them).
            environment = {key: value for key, value in os.environ.items() if not key.startswith('GIT_')}
            listing = subprocess.run(['git', '-C', str(root), 'ls-files', '-z', '--cached', '--others',
                                      '--exclude-standard'], capture_output=True, check=True, env=environment).stdout
            names = [name.decode('utf-8') for name in listing.split(b'\0') if name]
        except (OSError, subprocess.CalledProcessError):
            pass
    if names is None:
        names = [path.relative_to(root).as_posix() for path in root.rglob('*')
                 if not {'.git', '__pycache__'} & set(path.relative_to(root).parts)]
    return sorted(name for name in names if (root / name).is_file() and not (root / name).is_symlink())


# --- What a file is ------------------------------------------------------------------------------------------

def header_lines(style, holder):
    spdx = 'SPDX-License-Identifier: ' + LICENSE_ID
    copyright_line = 'Copyright %s %s' % (COPYRIGHT_YEAR, holder)
    if style == 'c':
        return ['/* %s */' % spdx, '/* %s */' % copyright_line]
    prefix = '//' if style == 'slashes' else '#'
    return ['%s %s' % (prefix, spdx), '%s %s' % (prefix, copyright_line)]


def is_outside(relative):
    parts = relative.split('/')
    return len(parts) == 1 or parts[0] in OUTSIDE


def classify(relative, head, exclusions):
    """(what, detail) for one file: what is 'source' (detail: its comment style), 'outside', 'data', 'generated',
    'excluded' (detail: the reason) or 'unclassified' (detail: what to do). `head` is the start of the file."""
    parts = relative.split('/')
    if is_outside(relative):
        return 'outside', None
    if parts[0] not in COVERED:
        return 'unclassified', 'a new top-level directory: add it to COVERED or OUTSIDE in tools/apply-spdx-headers.py'
    for glob, reason in exclusions:
        if fnmatch.fnmatchcase(relative, glob):
            return 'excluded', reason
    if GENERATED.search(b'\n'.join(head.split(b'\n')[:5])):
        return 'generated', None
    name, suffix = parts[-1], Path(parts[-1]).suffix
    if name in NAMES:
        return 'source', NAMES[name]
    if suffix in STYLES:
        return 'source', STYLES[suffix]
    if suffix in DATA:
        return 'data', None
    if not suffix and head.startswith(b'#!'):
        return 'source', 'hash'
    return 'unclassified', ('neither a known source type nor data: list it with a reason in %s, or teach '
                            'tools/apply-spdx-headers.py the type' % EXCLUSIONS_FILE)


# --- The header of one file ----------------------------------------------------------------------------------

def preamble(lines, style):
    """How many lines at the top stay above the header: a shebang, a coding line, the test declarations."""
    count = 1 if lines and lines[0].startswith(b'#!') else 0
    if style == 'hash':
        if count < 2 and count < len(lines) and CODING_LINE.match(lines[count]):
            count += 1
        while count < len(lines) and DECLARATION.match(lines[count]):
            count += 1
    return count


def edit_header(data, style, holder, replace=None):
    """(new data, action) for one source file. The action is 'unchanged', 'added', 'completed' (the copyright line
    was missing) or 'rewritten' (a line differed from the canonical text). HeaderProblem when the file must be left
    alone. `replace` is an old holder name whose copyright line may be rewritten to the current one."""
    if data.startswith(b'\xef\xbb\xbf'):
        raise HeaderProblem('starts with a byte order mark; remove it before the header is added')
    newline = b'\r\n' if data.split(b'\n', 1)[0].endswith(b'\r') else b'\n'
    lines = data.splitlines(keepends=True)
    spdx_text, copyright_text = header_lines(style, holder)
    window = [line.decode('utf-8', errors='replace').rstrip('\r\n') for line in lines[:WINDOW]]

    def ended(index):
        if not lines[index].endswith((b'\n', b'\r')):
            lines[index] += newline

    index = next((number for number, text in enumerate(window) if SPDX_LINE.match(text)), None)
    if index is None:
        if any(COPYRIGHT_LINE.match(text) for text in window):
            raise HeaderProblem('has a copyright notice of its own and no SPDX line, so it looks like third-party '
                                'code: list it in %s or merge the notices by hand' % EXCLUSIONS_FILE)
        position = preamble(lines, style)
        if position:
            ended(position - 1)
        lines[position:position] = [spdx_text.encode('utf-8') + newline, copyright_text.encode('utf-8') + newline]
        return b''.join(lines), 'added'
    identifier = SPDX_LINE.match(window[index]).group(1)
    own_line = window[index + 1] if index + 1 < len(window) else ''
    own = OWN_COPYRIGHT.match(own_line)
    legacy = (replace is not None and identifier in LEGACY_LICENSE_IDS and own is not None
              and own.group('name') in (holder, replace))
    if identifier != LICENSE_ID and not legacy:
        raise HeaderProblem('says SPDX-License-Identifier: %s, but first-party files are %s: fix it by hand'
                            % (identifier, LICENSE_ID))
    action = 'unchanged'
    if window[index] != spdx_text:
        lines[index] = spdx_text.encode('utf-8') + newline
        action = 'rewritten'
    following = index + 1
    if following < len(window) and COPYRIGHT_LINE.match(window[following]):
        if window[following] != copyright_text:
            own = OWN_COPYRIGHT.match(window[following])
            if own is None or own.group('name') not in (holder, replace):
                raise HeaderProblem('has the copyright line %r, expected %r: change it by hand, or after changing '
                                    '%s run this script with --replace-holder and the old name'
                                    % (window[following], copyright_text, HOLDER_FILE))
            lines[following] = copyright_text.encode('utf-8') + newline
            action = 'rewritten'
    else:
        ended(index)
        lines.insert(following, copyright_text.encode('utf-8') + newline)
        action = 'completed'
    return b''.join(lines), action


# --- The tree ------------------------------------------------------------------------------------------------

class Plan:
    """What the script would do to a tree: the new content by path, the problems, and a count of every kind of file."""

    def __init__(self):
        self.changes = {}
        self.problems = []
        self.counts = collections.Counter()


def plan_headers(root, holder, replace=None):
    root = Path(root)
    plan = Plan()
    exclusions, problems = read_exclusions(root)
    plan.problems += problems
    used = set()
    for relative in list_files(root):
        if is_outside(relative):
            plan.counts['outside'] += 1
            continue
        data = (root / relative).read_bytes()
        what, detail = classify(relative, data[:4096], exclusions)
        if what == 'excluded':
            used.update(glob for glob, _ in exclusions if fnmatch.fnmatchcase(relative, glob))
        if what == 'unclassified':
            plan.problems.append('%s: %s' % (relative, detail))
        if what != 'source':
            plan.counts[what] += 1
            continue
        try:
            new, action = edit_header(data, detail, holder, replace)
        except HeaderProblem as problem:
            plan.counts['problem'] += 1
            plan.problems.append('%s: %s' % (relative, problem))
            continue
        plan.counts[action] += 1
        if new != data:
            plan.changes[relative] = new
    # The exclusion list is written for the whole development tree. In a source publication some of the files it
    # names are not there, and an entry that matches nothing is expected; only the development tree checks for
    # entries that went stale.
    if (root / OUTSIDE[OUTSIDE.index('private')]).is_dir():
        plan.problems += ['%s: the entry %r matches no file; remove it' % (EXCLUSIONS_FILE, glob)
                          for glob, _ in exclusions if glob not in used]
    return plan


def identity_changes(root, holder):
    """({file: new text}, problems) for NOTICE, AUTHORS.md and README.md: the lines in IDENTITY get the name of the
    rights holder; a year other than the one in the headers is a problem."""
    root = Path(root)
    texts, problems = {}, []
    for name, pattern in IDENTITY:
        if not (root / name).is_file():
            continue
        text = texts.get(name)
        if text is None:
            text = (root / name).read_text(encoding='utf-8')
        matches = list(pattern.finditer(text))
        if len(matches) != 1:
            problems.append('%s: expected one line that matches %s, found %d' % (name, pattern.pattern, len(matches)))
            continue
        match = matches[0]
        if 'year' in pattern.groupindex and match.group('year') != COPYRIGHT_YEAR:
            problems.append('%s: the copyright year is %s, the headers say %s' % (name, match.group('year'),
                                                                                  COPYRIGHT_YEAR))
        texts[name] = text[:match.start('name')] + holder + text[match.end('name'):]
    changed = {name: text for name, text in texts.items() if text != (root / name).read_text(encoding='utf-8')}
    return changed, problems


def identity_problems(root, holder=None):
    """What differs between legal/RIGHTS_HOLDER and the public files that name the rights holder."""
    holder = holder or read_rights_holder(root)
    changed, problems = identity_changes(root, holder)
    return problems + ['%s does not name the rights holder %s (%s)' % (name, holder, HOLDER_FILE)
                       for name in sorted(changed)]


def header_problems(root, holder=None, replace=None):
    """What is wrong with the headers of the tree, as sentences: files that need one, conflicts, bad exclusions."""
    holder = holder or read_rights_holder(root)
    plan = plan_headers(root, holder, replace)
    return ['%s: needs its header (tools/apply-spdx-headers.py adds it)' % name for name in sorted(plan.changes)] \
        + plan.problems


# --- The command ---------------------------------------------------------------------------------------------

def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('--check', action='store_true', help='change nothing; exit 1 if a change or a problem is found')
    parser.add_argument('--replace-holder', metavar='OLD',
                        help='also rewrite the copyright lines that name OLD, after the rights holder was changed')
    parser.add_argument('--root', type=Path, default=ROOT, help='the repository (default: the one this script is in)')
    parser.add_argument('-v', '--verbose', action='store_true', help='name every file that is changed')
    args = parser.parse_args(argv)
    root = args.root.resolve()
    holder = read_rights_holder(root)
    plan = plan_headers(root, holder, args.replace_holder)
    texts, identity = identity_changes(root, holder)
    problems = plan.problems + identity
    pending = sorted(plan.changes) + sorted(texts)
    if args.check:
        problems += ['%s: out of date (tools/apply-spdx-headers.py brings it up to date)' % name for name in pending]
    else:
        for relative, data in plan.changes.items():
            (root / relative).write_bytes(data)
        for name, text in texts.items():
            (root / name).write_text(text, encoding='utf-8')
        if args.verbose:
            for name in pending:
                print('  changed %s' % name)
    counts = plan.counts
    print('apply-spdx-headers: %d source files (%d unchanged, %d added, %d completed, %d rewritten); not touched: '
          '%d generated, %d excluded, %d data, %d outside the covered directories; rights holder %s'
          % (sum(counts[kind] for kind in ('unchanged', 'added', 'completed', 'rewritten')), counts['unchanged'],
             counts['added'], counts['completed'], counts['rewritten'], counts['generated'], counts['excluded'],
             counts['data'], counts['outside'], holder))
    if problems:
        print('apply-spdx-headers: %d problem(s):' % len(problems), file=sys.stderr)
        for problem in problems:
            print('  - ' + problem, file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
